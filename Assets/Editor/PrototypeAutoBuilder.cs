        private static void CreateExitZone(Vector3 position, Vector3 scale, LocationLoader loader)
        {
            var zone = GameObject.CreatePrimitive(PrimitiveType.Cube);
            zone.name = "ExitZone";
            zone.transform.position = position;
            zone.transform.localScale = scale;

            var renderer = zone.GetComponent<Renderer>();
            renderer.sharedMaterial = CreateColorMaterial(
                "ExitZoneGreen", new Color(0.10f, 0.85f, 0.25f, 0.30f));

            var collider = zone.GetComponent<BoxCollider>();
            collider.isTrigger = true;

            var exit = zone.AddComponent<ExitZone>();
            BindObject(exit, "loader", loader);
            BindString(exit, "worldMapScene", "WorldMap");
        }

