        static PrototypeAutoBuilder()
        {
            EditorApplication.delayCall += AutoBuildIfNeeded;
        }

        [MenuItem("Survival Game/Rebuild Playable Prototype")]
        public static void RebuildFromMenu()
        {
            BuildAll();
        }

        private static void AutoBuildIfNeeded()
        {
            if (EditorApplication.isPlayingOrWillChangePlaymode || EditorApplication.isCompiling || File.Exists(Marker))
                return;

            BuildAll();
        }

        private static void BuildAll()
        {
            EnsureFolder("Assets", "Generated");
            EnsureFolder("Assets", "Scenes");

            BuildCharacterCreator();
            BuildWorldMap();
            BuildLocation("HomeBase", false);
            BuildLocation("ForestLocation", true);

            EditorBuildSettings.scenes = new[]
            {
                new EditorBuildSettingsScene(ScenesFolder + "/CharacterCreator.unity", true),
                new EditorBuildSettingsScene(ScenesFolder + "/WorldMap.unity", true),
                new EditorBuildSettingsScene(ScenesFolder + "/HomeBase.unity", true),
                new EditorBuildSettingsScene(ScenesFolder + "/ForestLocation.unity", true)
            };

            File.WriteAllText(Marker,
                "Generated by PrototypeAutoBuilder. Delete this file or use Survival Game > Rebuild Playable Prototype to rebuild.");
            AssetDatabase.Refresh();
            AssetDatabase.SaveAssets();

            EditorSceneManager.OpenScene(ScenesFolder + "/CharacterCreator.unity");
            Debug.Log("Survival Game prototype scenes generated successfully.");
        }

