        private static void BuildLocation(string sceneName, bool forest)
        {
            var scene = EditorSceneManager.NewScene(NewSceneSetup.EmptyScene, NewSceneMode.Single);
            CreateWorldLighting();

            var ground = GameObject.CreatePrimitive(PrimitiveType.Plane);
            ground.name = forest ? "Forest Ground" : "Home Ground";
            ground.transform.localScale = new Vector3(6f, 1f, 6f);
            ground.GetComponent<Renderer>().sharedMaterial = CreateColorMaterial(
                sceneName + "_Ground",
                forest ? new Color(0.17f, 0.25f, 0.14f) : new Color(0.27f, 0.24f, 0.18f));

            if (forest)
                CreateForestProps();
            else
                CreateHomeProps();

            var player = CreatePrototypePlayer();

            var cameraGo = new GameObject("Main Camera");
            var camera = cameraGo.AddComponent<Camera>();
            camera.tag = "MainCamera";
            cameraGo.AddComponent<IsometricCameraFollow>().Bind(player.transform);
            camera.fieldOfView = 48f;

            var loaderGo = new GameObject("LocationLoader");
            var loader = loaderGo.AddComponent<LocationLoader>();

            CreateExitZone(new Vector3(0f, 0.5f, 28f), new Vector3(20f, 1f, 4f), loader);
            CreateExitZone(new Vector3(0f, 0.5f, -28f), new Vector3(20f, 1f, 4f), loader);
            CreateExitZone(new Vector3(28f, 0.5f, 0f), new Vector3(4f, 1f, 20f), loader);
            CreateExitZone(new Vector3(-28f, 0.5f, 0f), new Vector3(4f, 1f, 20f), loader);

            CreateGameplayHud(player);

            EditorSceneManager.SaveScene(scene, ScenesFolder + "/" + sceneName + ".unity");
        }

